/** Translates a German source string into the target language. Falls back to the source. */
export function translate(lang: Lang, de: string): string {
  return lang === 'en' ? (en[de] ?? de) : de;
}

type I18nValue = { lang: Lang; setLang: (lang: Lang) => void; t: (de: string) => string; locale: string };
const I18nContext = createContext<I18nValue>({ lang: 'de', setLang: () => {}, t: (de) => de, locale: 'de-DE' });

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('de');
  useEffect(() => { setLangState(readLang((k) => window.localStorage.getItem(k))); }, []);
  const setLang = (next: Lang) => {
    setLangState(next);
    try { window.localStorage.setItem(STORAGE_KEY, next); } catch { /* storage unavailable */ }
  };
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const value: I18nValue = { lang, setLang, t: (de) => translate(lang, de), locale: lang === 'de' ? 'de-DE' : 'en-GB' };
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() { return useContext(I18nContext); }

